def render(text: str, font: str = "default") -> str:
    """Render text as ASCII art banner."""
    chars = _FONTS.get(font, _FONTS["default"])
    lines = [""] * 5
    for ch in text.upper():
        glyph = chars.get(ch, chars.get(" ", ["    "] * 5))
        for i, row in enumerate(glyph):
            lines[i] += row + "  "
    return "\n".join(lines)

